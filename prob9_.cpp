// 72, 85, 91

#include <iostream>
using namespace std;

int main()
{
    int score_sub_1 = 72;
    int score_sub_2 = 85;
    int score_sub_3 = 91;

    cout << "Total score is: " << score_sub_1 + score_sub_2 + score_sub_3 << endl;
    cout << "Average score is: " << (score_sub_1 + score_sub_2 + score_sub_3) / 3 << endl;
}
